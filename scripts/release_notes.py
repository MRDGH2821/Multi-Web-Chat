#!/usr/bin/env python3
"""Build GitHub release notes from package.json and CHANGELOG.md.

The release tag is `v` plus the version in package.json. The notes are the
git-cliff section headed `## [version]` in CHANGELOG.md.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def release_tag(version: str) -> str:
    if not version or version.startswith("v"):
        raise SystemExit(f"package.json version is not a bare version: {version}")
    return f"v{version}"


def normalize_tag(tag: str) -> str:
    tag = tag.strip()
    prefix = "refs/tags/"
    if tag.startswith(prefix):
        return tag[len(prefix) :]
    return tag


def changelog_section(text: str, version: str) -> str:
    heading = f"## [{version}]"
    lines = text.splitlines()
    start = next((i for i, line in enumerate(lines) if line.startswith(heading)), None)
    if start is None:
        raise SystemExit(f"CHANGELOG.md has no section headed {heading}")

    end = next(
        (i for i in range(start + 1, len(lines)) if lines[i].startswith("## [")),
        len(lines),
    )
    section = lines[start:end]
    footer = "<!-- generated by git-cliff -->"
    section = [line for line in section if footer not in line]
    while section and section[-1].strip() in {"", "---"}:
        section.pop()
    if not any(line.strip() for line in section):
        raise SystemExit(f"CHANGELOG.md section for {version} is empty")
    return "\n".join(section).rstrip() + "\n"


def write_output(path: Path | None, values: dict[str, str]) -> None:
    lines = [f"{key}={value}" for key, value in values.items()]
    if path is None:
        print("\n".join(lines))
        return
    with path.open("a", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path, default=Path("package.json"))
    parser.add_argument("--changelog", type=Path, default=Path("CHANGELOG.md"))
    parser.add_argument("--tag", required=True, help="Git tag being released")
    parser.add_argument("--notes", type=Path, required=True)
    parser.add_argument("--github-output", type=Path)
    args = parser.parse_args()

    if not args.package.is_file():
        raise SystemExit(f"Missing {args.package}")
    if not args.changelog.is_file():
        raise SystemExit(f"Missing {args.changelog}")

    payload = json.loads(args.package.read_text(encoding="utf-8"))
    version = payload.get("version")
    if not isinstance(version, str):
        raise SystemExit("package.json version is missing")

    expected = release_tag(version)
    given = normalize_tag(args.tag)
    if given != expected:
        raise SystemExit(f"Tag {given} does not match package.json version {expected}")

    notes = changelog_section(args.changelog.read_text(encoding="utf-8"), version)
    args.notes.write_text(notes, encoding="utf-8")
    write_output(
        args.github_output,
        {
            "prerelease": "true" if "-" in version else "false",
            "tag": expected,
            "version": version,
        },
    )


if __name__ == "__main__":
    sys.exit(main())
